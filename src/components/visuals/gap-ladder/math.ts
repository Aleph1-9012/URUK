export type EnergyWeight = { energy: number; gap: number; count: number; each: number; total: number };

export function thermalState(beta: number): { weights: EnergyWeight[]; purity: number; defect: number; groundWeight: number; otherWeight: number } {
  let partition = 0;

  for (const level of LEVELS) partition += level.count * Math.exp(-beta * (level.energy - GROUND_ENERGY));

  let purity = 0;
  let otherWeight = 0;
  const weights = LEVELS.map(level => {
    const gap = level.energy - GROUND_ENERGY;
    const each = Math.exp(-beta * gap) / partition;
    const total = level.count * each;
    purity += level.count * each * each;

    if (gap > 2.2) otherWeight += total;

    return { energy: level.energy, gap, count: level.count, each, total };
  });

  return { weights, purity, defect: 1 - purity, groundWeight: 1 / partition, otherWeight };
}

export function defectAfterSquare(defect: number): number {
  return defect * defect / (2 * (1 - defect) ** 2);
}

export function gapFromPurity(beta: number, purity: number): number | null {
  return purity > .5 ? Math.log(purity / (1 - purity)) / beta : null;
}

export function doublingStep(step: number): { sites: number; beta: number; power: number } {
  const power = 2 ** step;

  return { sites: 60 * power, beta: 105 / 4 * power, power };
}

export type RingState = { length: number; spin: .5 | 1; gap: number | null; settled: boolean };

function eased(time: number, start: number, end: number): number {
  const progress = Math.max(0, Math.min(1, (time - start) / (end - start)));

  return progress * progress * (3 - 2 * progress);
}

function sequence(time: number, start: number, period: number, spin: .5 | 1, gaps: readonly number[], beforeLength: number, beforeGap: number): RingState {
  const first = gaps[0];

  if (first === undefined) throw new Error('A ring sequence needs at least one computed gap.');

  if (time < start + 800) {
    const amount = eased(time, start, start + 800);

    return { length: beforeLength + (4 - beforeLength) * amount, spin, gap: beforeGap + (first - beforeGap) * amount, settled: false };
  }

  const origin = start + 800;
  const index = Math.min(gaps.length - 1, Math.floor((time - origin) / period));
  const previous = Math.max(0, index - 1);
  const from = gaps[previous];
  const to = gaps[index];

  if (from === undefined || to === undefined) throw new Error('The current ring needs both neighbouring computed gaps.');

  const amount = index === 0 ? 1 : eased(time, origin + index * period, origin + (index + .65) * period);

  return { length: 4 + 2 * (previous + (index - previous) * amount), spin, gap: from + (to - from) * amount, settled: amount === 1 };
}

// Numerical labels are shown only when settled. In-between positions carry the
// same ladder from one computed ring to the next; they are not extra calculations.
export function ringState(time: number): RingState {
  if (time < 14500) return { length: 8, spin: 1, gap: ONE_GAPS[2], settled: true };
  if (time < 23000) return sequence(time, 14500, 800, .5, HALF_GAPS, 8, ONE_GAPS[2]);
  if (time < 31000) return sequence(time, 23000, 1000, 1, ONE_GAPS, 20, HALF_GAPS[8]);

  if (time < 33000) {
    const amount = eased(time, 31000, 33000);

    return { length: 14 - 6 * amount, spin: 1, gap: ONE_GAPS[5] + (ONE_GAPS[2] - ONE_GAPS[5]) * amount, settled: amount === 1 };
  }

  if (time >= 69500 && time < 77000) {
    const length = 8 + eased(time, 69500, 71000) - eased(time, 74500, 77000);

    return { length, spin: 1, gap: null, settled: time >= 71000 && time <= 74500 };
  }

  return { length: 8, spin: 1, gap: ONE_GAPS[2], settled: true };
}

export function energyBeta(time: number): number {
  const doubling = eased(time, 86400, 87500) + eased(time, 88400, 89500) + eased(time, 90400, 91500);

  return 2 ** (1 + doubling);
}

