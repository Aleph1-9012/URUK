import { expect, test } from 'bun:test';
import { FAMILY_EXAMPLES } from '../src/components/visuals/remainder-clock/data';
import { createArtinModel, familyGates, gates, modPow, modPowBigInt, orbit, primesUpTo } from '../src/components/visuals/remainder-clock/math';

function trialPrime(value: number): boolean {
  if (value < 2) return false;

  for (let divisor = 2; divisor * divisor <= value; divisor++) {
    if (value % divisor === 0) return false;
  }

  return true;
}

function bruteOrder(base: number, prime: number): number {
  let value = 1;

  for (let exponent = 1; exponent < prime; exponent++) {
    value = value * base % prime;

    if (value === 1) return exponent;
  }

  throw new Error('The test base must be invertible modulo its prime.');
}

test('029: the clocks and index gates agree, including early cycles and open gates', () => {
  for (const [base, prime, residues] of [
    [2, 11, [2, 4, 8, 5, 10, 9, 7, 3, 6, 1]],
    [2, 7, [2, 4, 1]],
    [4, 11, [4, 5, 9, 3, 1]],
    [2, 31, [2, 4, 8, 16, 1]],
    [2, 13, [2, 4, 8, 3, 6, 12, 11, 9, 5, 10, 7, 1]],
  ] as const) {
    const clock = orbit(base, prime);
    expect(clock.residues).toEqual([...residues]);
    expect(clock.order).toBe(bruteOrder(base, prime));
    expect(new Set(clock.residues).size).toBe(clock.order);
    expect(clock.residues.includes(0)).toBe(false);
  }

  for (let prime = 3; prime < 250; prime += 2) {
    if (!trialPrime(prime)) continue;

    for (let base = 2; base <= 7; base++) {
      if (base % prime === 0) continue;

      const order = bruteOrder(base, prime);
      const index = (prime - 1) / order;
      const checks = gates(base, prime);
      expect(checks.some(gate => gate.closed)).toBe(order !== prime - 1);

      for (const gate of checks) expect(gate.closed).toBe(index % gate.q === 0);
    }
  }

  expect(gates(2, 31).map(gate => [gate.q, gate.remainder, gate.closed])).toEqual([[2, 1, true], [3, 1, true], [5, 2, false]]);
  expect(gates(2, 13).map(gate => [gate.q, gate.remainder, gate.closed])).toEqual([[2, 12, false], [3, 3, false]]);
  expect(() => orbit(2, 4)).toThrow();
  expect(() => orbit(11, 11)).toThrow();
  expect(() => modPow(2, 3, 100_000_000)).toThrow();
});

test('029: the live prime strip, 100,000 tally and interval counts match independent orbits and the reference sample', () => {
  const model = createArtinModel();
  const expectedPrimes: number[] = [];

  for (let prime = 3; prime <= 1_993; prime += 2) {
    if (trialPrime(prime)) expectedPrimes.push(prime);
  }

  expect(model.strip.map(mark => mark.prime)).toEqual(expectedPrimes);

  for (const mark of model.strip) expect(mark.primitive).toBe(bruteOrder(2, mark.prime) === mark.prime - 1);

  expect(model.stripTallies.map(row => row.count)).toEqual([6, 13, 24, 42, 77, 116]);
  expect(model.tallies.slice(0, 3).map(row => [row.count, row.total])).toEqual([[67, 167], [470, 1_228], [3_603, 9_591]]);
  expect(model.intervals.slice(0, 3).map(row => [row.count, row.total])).toEqual([[10, 21], [50, 135], [370, 1_033]]);

  const referencePartials = [0.50000, 0.41667, 0.39583, 0.38641, 0.38290, 0.38044, 0.37904, 0.37793];
  expect(model.partials.map(row => Number(row.product.toFixed(5)))).toEqual(referencePartials);
  expect(Number(model.product.toFixed(5))).toBe(0.37396);

  for (const tail of model.tails) expect(tail.share).toBeLessThan(1 / (tail.from - 1));

  const footnotePrimes = primesUpTo(5_000).filter(prime => (prime - 1) % 4 === 0 && trialPrime((prime - 1) / 4));

  for (const prime of footnotePrimes) expect(bruteOrder(2, prime)).toBe(prime - 1);
});

test('029: the 26-digit family primes keep every gate open or shut only gate 11, using exact integer powers', () => {
  // Python pow results, independently regenerated by the direction's script.
  const remainders = {
    open: ['14872000000000000000151866', '7759892772862085519443643', '2185885006294184655622144', '1077450437678401297199962'],
    closed: ['14872000000000000003673098', '1', '4320479506036660499270280', '5716579653003390563517011'],
  } as const;

  for (const kind of ['open', 'closed'] as const) {
    const example = FAMILY_EXAMPLES[kind];
    const prime = BigInt(example.prime);
    const checks = familyGates(example.prime, example.largeFactor);
    const closed: string[] = [];

    for (const gate of checks) {
      if (gate.closed) closed.push(gate.q.toString());
    }

    expect(checks.map(gate => gate.remainder.toString())).toEqual([...remainders[kind]]);
    expect(closed).toEqual(kind === 'open' ? [] : ['11']);
    expect(modPowBigInt(2n, prime - 1n, prime)).toBe(1n);
    expect(checks[0]?.remainder).toBe(prime - 1n);
    expect(prime % 8n).toBe(3n);

    for (const gate of checks) expect(modPowBigInt(gate.remainder, gate.q, prime)).toBe(1n);
  }

  expect(() => familyGates(FAMILY_EXAMPLES.open.prime, FAMILY_EXAMPLES.closed.largeFactor)).toThrow();
});
